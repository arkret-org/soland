-- Squashed initial migration (soland).
--
-- Event references in this file appear as `<role>_event_id` and
-- `<role>_event_ref`. That is not drift: the suffix is normative and comes from
-- `arkret-spec zh/models/common-fields.md` 2.1. `_id` names the Event as the
-- artifact the row is about -- an operation target, audit target or selector
-- target (`retention_tombstones.event_id`, `moderation_reports.target_event_id`,
-- `mls_key_packages.device_authorize_event_id`). `_ref` names an Event used as
-- causal, finality or proof material (`contacts.request_event_ref`,
-- `agent_sidecar_contexts.predecessor_event_ref`,
-- `agent_principals.authorized_event_ref`). A column MUST carry the same name
-- as the spec field it materializes.
--
-- The suffix says nothing about storage type: both forms hold the same
-- 33-octet token as `canonical_events.id`, in `bytea`. An Event reference is
-- only an `event_pk` foreign key when the row requires that Event to be
-- admitted here and to stay; otherwise the identity is stored directly, so
-- peer-authored and erased Events remain expressible.
-- Final schema as of 2026-06-10, consolidated from the previous migration chain
-- (generated by applying all historical migrations and dumping the resulting schema).

-- Clean-break fence for the suite-tagged full-digest Event/Realm identity
-- layout.  Startup verifies this singleton after Diesel migrations run, so a
-- database that recorded the old squashed migration version but still has the
-- UUID schema cannot be opened silently.
